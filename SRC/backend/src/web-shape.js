export function shape(row) {
  if (row == null) return row;
  if (Array.isArray(row)) return row.map(shape);
  const result = Object.fromEntries(
    Object.entries(row).map(([key, value]) => [names[key] || key, value]),
  );
  if (row.DiaChi !== undefined)
    result.address = result.defaultAddress = row.DiaChi;
  if (row.NoiDung !== undefined) result.text = result.body = row.NoiDung;
  if (row.KyThuatVienId !== undefined)
    result.technicianId = result.assignedTechnicianId = row.KyThuatVienId;
  if (row.PhuongThuc !== undefined) result.method = row.PhuongThuc;
  if (row.Loai !== undefined) result.type = row.Loai;
  if (row.NgayCapNhat !== undefined) result.updatedAt = row.NgayCapNhat;
  if (row.TongTien !== undefined) result.total = row.TongTien;
  if (row.ChungTuId !== undefined) result.proofId = row.ChungTuId;
  if (row.Diem !== undefined) result.rating = row.Diem;
  if (row.PhienBan !== undefined) result.version = row.PhienBan;
  if (row.DaDoc !== undefined) result.readAt = row.DaDoc ? row.NgayTao : null;
  return result;
}
export const sum = (rows, key) =>
  rows.reduce((total, row) => total + Number(row[key] || 0), 0);
export const latest = (rows) => rows?.[0] || null;
